package es.um.arso.compraventa.servicio.puertos;

public class UsuarioInfo {
    private String id;
    private String nombre;

    public UsuarioInfo() {}

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }
}
